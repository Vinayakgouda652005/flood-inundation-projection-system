
from typing import List

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from app.core.database import get_db
from app.models.prediction import Prediction
from app.models.prediction_request import PredictionRequest
from app.schemas.prediction import (
    PredictionRequestCreate,
    PredictionResponse,
    PredictionHistoryItem,
    PredictionRecordCreate,
)
from app.services.prediction_service import prediction_service


router = APIRouter(prefix="/api/predict", tags=["Prediction"])


@router.post(
    "",
    response_model=PredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Predict Flood",
    description=(
        "Creates a prediction request in PostgreSQL, retrieves available "
        "environmental data, validates the required trained-model features, "
        "and runs AI model inference when all required features are available. "
        "If features are missing, the request is saved without fabricating "
        "a probability. Inundation geometry is not generated by this endpoint."
    ),
)
def predict_flood(
    request_data: PredictionRequestCreate,
    db: Session = Depends(get_db),
):
    return prediction_service.process_prediction_request(
        db=db,
        request_data=request_data,
    )


@router.get(
    "/history",
    response_model=List[PredictionHistoryItem],
    summary="Get Prediction History",
)
def get_prediction_history(
    limit: int = Query(50, ge=1, le=100),
    db: Session = Depends(get_db),
):
    return prediction_service.get_history(db=db, limit=limit)


@router.get(
    "/{request_id}",
    response_model=PredictionResponse,
    summary="Get Prediction By ID",
)
def get_prediction_by_id(
    request_id: int,
    db: Session = Depends(get_db),
):
    result = prediction_service.get_by_id(
        db=db,
        request_id=request_id,
    )

    if result is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Prediction request not found",
        )

    return result


@router.post(
    "/record",
    status_code=status.HTTP_201_CREATED,
    summary="Record Prediction Result",
)
def record_prediction_result(
    record: PredictionRecordCreate,
    db: Session = Depends(get_db),
):
    """
    Save or update a prediction result for an existing request.
    """
    try:
        request_record = (
            db.query(PredictionRequest)
            .filter(PredictionRequest.id == record.prediction_request_id)
            .first()
        )

        if request_record is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Prediction request ID does not exist",
            )

        prediction = (
            db.query(Prediction)
            .filter(
                Prediction.prediction_request_id == request_record.id
            )
            .first()
        )

        if prediction is None:
            prediction = Prediction(
                prediction_request_id=request_record.id,
                flood_probability=record.flood_probability,
                risk_level=record.risk_level,
                flood_occurred=record.flood_occurred,
            )
            db.add(prediction)
        else:
            prediction.flood_probability = record.flood_probability
            prediction.risk_level = record.risk_level
            prediction.flood_occurred = record.flood_occurred

        request_record.status = "COMPLETED"
        db.commit()

        return {
            "message": "Prediction record saved successfully",
            "request_id": request_record.id,
        }

    except HTTPException:
        db.rollback()
        raise
    except Exception as exc:
        db.rollback()
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Could not save the prediction result",
        ) from exc
